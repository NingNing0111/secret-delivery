import { test, expect, type Page } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { getTestDatabaseUrl } from '../helpers/database';
const db = new PrismaClient({ datasources: { db: { url: getTestDatabaseUrl() } } });
const secret = 'synthetic-admin-private-123456';
async function login(page: Page) {
  await page.goto('/admin');
  await expect(page).toHaveURL(/\/admin\/login/);
  await page.getByLabel('管理员密码').fill(process.env.ADMIN_PASSWORD!);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '仪表盘' })).toBeVisible();
}
async function create(page: Page) {
  await page.goto('/admin/secrets/create');
  await page.getByLabel('卡密内容').fill(` ${secret}\n\n${secret}\nsynthetic-second-content`);
  await expect(page.getByText('已识别：3 条', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '生成链接', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('成功 3');
}
test.beforeEach(async () => { await db.secret.deleteMany(); await db.adminSession.deleteMany(); });
test.afterAll(async () => { await db.$disconnect(); });
test('admin complete flow keeps secrets private until explicit Reveal, exports links and confirms deletion', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await login(page); await create(page);
  expect(await page.content()).not.toContain(secret);
  const rows = await db.secret.findMany({ orderBy: { batchIndex: 'asc' } });
  expect(rows).toHaveLength(3);
  await page.getByRole('button', { name: '复制第 1 条链接', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(`http://127.0.0.1:3100/k/${rows[0].token}`);
  await page.getByRole('button', { name: '复制全部链接' }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(rows.map(r => `http://127.0.0.1:3100/k/${r.token}`).join('\n'));
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 CSV', exact: true }).click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  const chunks = []; for await (const chunk of stream!) chunks.push(chunk);
  const csv = Buffer.concat(chunks).toString();
  expect(csv).toContain('index,url'); expect(csv).not.toContain(secret);
  expect(csv.trim().split(/\r?\n/).slice(1)).toEqual(rows.map((row, index) => `${index + 1},http://127.0.0.1:3100/k/${row.token}`));
  await page.goto('/admin/secrets');
  await page.getByLabel('Token 或 ID').fill(rows[0].token);
  await page.getByRole('button', { name: '筛选', exact: true }).click();
  await expect(page.getByRole('link', { name: '详情', exact: true })).toHaveCount(1);
  const payloads: string[] = [];
  // Buffer the actual server response before delivery. CDP response.text() can
  // lose its resource during concurrent Next navigation, even for this URL.
  const detailUrl = (url: URL) => url.pathname === `/admin/secrets/${rows[0].id}`;
  await page.route(detailUrl, async route => {
    const response = await route.fetch();
    expect(response.ok()).toBe(true);
    const body = await response.body();
    payloads.push(body.toString('utf8'));
    await route.fulfill({ response, body });
    await response.dispose();
  });
  await page.getByRole('link', { name: '详情', exact: true }).click();
  await expect(page.getByRole('heading', { name: '卡密详情' })).toBeVisible();
  expect(await page.content()).not.toContain(secret);
  await page.unrouteAll({ behavior: 'wait' });
  expect(payloads.length).toBeGreaterThan(0);
  expect(payloads.join('')).toContain(rows[0].id);
  expect(payloads.join('')).toContain('"preview"');
  expect(payloads.join('')).not.toContain(secret);
  const initial = await page.request.get(`/admin/secrets/${rows[0].id}`);
  expect(initial.ok()).toBe(true);
  expect(initial.headers()['cache-control']).toContain('no-store');
  const initialHtml = await initial.text();
  expect(initialHtml).toContain(rows[0].id);
  expect(initialHtml).not.toContain(secret);
  await page.getByRole('button', { name: 'Reveal 查看完整内容' }).click();
  await expect(page.getByTestId('revealed-content')).toHaveText(secret);
  expect((await db.secret.findUniqueOrThrow({ where: { id: rows[0].id } })).viewCount).toBe(0);
  await page.getByRole('button', { name: '禁用', exact: true }).click();
  await expect(page.getByRole('button', { name: '恢复', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '恢复', exact: true }).click();
  await expect(page.getByRole('button', { name: '禁用', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.goto('/admin/secrets');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.getByLabel('选择本页').check();
  await page.getByRole('button', { name: '批量删除' }).click();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  expect(await db.secret.count()).toBe(3);
  await page.getByRole('button', { name: '批量删除' }).click();
  await page.getByRole('button', { name: '确认永久删除' }).click();
  await expect(page.getByText('暂无记录')).toBeVisible();
  expect(await db.secret.count()).toBe(0);
  await page.getByRole('button', { name: '退出登录' }).click();
  await expect(page).toHaveURL(/\/admin\/login/);
  await page.goto('/admin/secrets'); await expect(page).toHaveURL(/\/admin\/login/);
});
