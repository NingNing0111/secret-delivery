test('uncertain creation is not retried, double submission is blocked and mobile form fits', async ({ page }) => {
  await login(page);
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto('/admin/secrets/create');
  await page.getByLabel('卡密内容').fill(secret);
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  let calls = 0;
  await page.route('**/api/admin/secrets/batch', async route => { calls++; await gate; await route.abort(); });
  await page.getByRole('button', { name: '生成链接', exact: true }).click();
  await expect(page.getByRole('button', { name: '生成中…' })).toBeDisabled();
  release();
  await expect(page.getByRole('alert').filter({ hasText: '结果不确定' })).toBeVisible();
  expect(calls).toBe(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
});
